import { readFile, readdir, mkdir, writeFile } from 'node:fs/promises';

const root = new URL('./', import.meta.url);
const names = (await readdir(new URL('migrations/', root))).filter(name => name.endsWith('.sql')).sort();
const sources = await Promise.all(names.map(async name => ({ name, sql: await readFile(new URL(`migrations/${name}`, root), 'utf8') })));
const tables = ['games', 'levels', 'questions', 'question_answers', 'level_questions', 'admin_users', 'player_progress', 'media_records'];
const outputs = new Map();
for (const fresh of [true, false]) {
  const file = fresh ? 'setup_fresh.sql' : 'upgrade_existing.sql';
  const selected = fresh ? sources : sources.slice(1);
  const guard = fresh
    ? `if exists (select 1 from unnest(array[${tables.map(name => `'public.${name}'`).join(', ')}]) t(name) where to_regclass(t.name) is not null) then\n    raise exception 'Yapnix tables already exist. Use upgrade_existing.sql instead.';\n  end if;`
    : `if exists (select 1 from unnest(array[${tables.map(name => `'public.${name}'`).join(', ')}]) t(name) where to_regclass(t.name) is null) then\n    raise exception 'Initial Yapnix schema is missing or incomplete. Use setup_fresh.sql only for an empty project.';\n  end if;`;
  outputs.set(`sql-editor/${file}`, `-- Generated by npm run sql:generate. Do not edit this file directly.\n-- ${fresh ? 'FRESH project only: migrations 001 onward, including private Storage.' : 'EXISTING initial Yapnix schema: migrations 002 onward, including private Storage.'}\n-- Paste this entire file into Supabase SQL Editor and Run as postgres.\n-- All changes succeed together or roll back together. No tables or content are deleted.\nbegin;\ndo $$ begin\n  ${guard}\nend $$;\n\n${selected.map(({ name, sql }) => `-- Migration: ${name}\n${sql.trim()}\n`).join('\n')}\ncommit;\n`);
}
const storage = sources.find(source => source.name === '202610090006_private_content_storage.sql');
outputs.set('storage_setup.sql', `-- Generated compatibility shortcut for migration 006.\n-- Run in Supabase SQL Editor as postgres; safe to reapply.\nbegin;\n${storage.sql.trim()}\ncommit;\n`);
const editorUpgrade = sources.find(source => source.name === '202610130008_game_prompts_and_draft_edits.sql');
outputs.set('sql-editor/upgrade_game_editor.sql', `-- Generated by npm run sql:generate.
-- For installations that already applied migration 007 (categories).
-- Run in Supabase SQL Editor as postgres. No images or questions are deleted.
begin;
do $$ begin
  if to_regclass('public.game_categories') is null then
    raise exception 'Apply upgrade_existing.sql first to install game categories.';
  end if;
end $$;
${editorUpgrade.sql.trim()}
commit;
`);
outputs.set('sql-editor/upgrade_catalog_artwork.sql', `-- Generated by npm run sql:generate. Requires migrations 001–008.\nbegin;\n${sources.find(source => source.name === '202610260009_catalog_artwork.sql').sql.trim()}\ncommit;\n`);
outputs.set('sql-editor/upgrade_icon_library.sql', `-- Generated by npm run sql:generate. Requires migrations 001–008. Includes 009 artwork and 010 library icons.\nbegin;\n${sources.filter(source => source.name >= '202610260009').map(source => source.sql.trim()).join('\n\n')}\ncommit;\n`);
await mkdir(new URL('sql-editor/', root), { recursive: true });
for (const [name, sql] of outputs) {
  const target = new URL(name, root);
  if (process.argv.includes('--check')) {
    if (await readFile(target, 'utf8').catch(() => '') !== sql) throw new Error(`${name} is stale; run npm run sql:generate`);
  } else await writeFile(target, sql);
}
console.log(process.argv.includes('--check') ? 'SQL bundles match migrations.' : 'SQL Editor bundles generated.');
