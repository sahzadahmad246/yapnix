import { readFile, writeFile, mkdir, readdir } from 'node:fs/promises';
const root = new URL('../', import.meta.url);
const icons = JSON.parse(await readFile(new URL('shared/catalog-icons/catalog.json', root), 'utf8'));
const outputs = new Map();
const keys = new Set();
for (const icon of icons) {
  if (!/^[a-z]+(?:-[a-z]+)*$/.test(icon.key) || keys.has(icon.key) || !/^#[0-9A-F]{6}$/.test(icon.color)) throw new Error(`Invalid icon: ${icon.key}`);
  keys.add(icon.key);
  const svg = await readFile(new URL(`shared/catalog-icons/svg/${icon.key}.svg`, root), 'utf8');
  if (/\b(?:transform|stroke|style)=|<(?!\/?(?:svg|path)\b)/.test(svg)) throw new Error(`Unsupported SVG element in ${icon.key}`);
  const paths = [...svg.matchAll(/<path\b([^>]+)\/>/g)].map(([, attrs]) => {
    const d = attrs.match(/\bd="([^"]+)"/)?.[1];
    if (!d) throw new Error(`Missing path in ${icon.key}`);
    const alpha = attrs.match(/\bopacity="([^"]+)"/)?.[1] ?? '1';
    const fillType = attrs.includes('fill-rule="evenodd"') ? 'evenOdd' : 'nonZero';
    return `    <path android:fillColor="${icon.color}" android:fillAlpha="${alpha}" android:fillType="${fillType}" android:pathData="${d}" />`;
  });
  if (!paths.length) throw new Error(`No paths in ${icon.key}`);
  outputs.set(`admin/public/catalog-icons/${icon.key}.svg`, `${svg.replace('fill="currentColor"', `fill="${icon.color}"`)}\n`);
  outputs.set(`android/app/src/main/res/drawable/catalog_${icon.key.replaceAll('-', '_')}.xml`, `<!-- Generated from Phosphor Icons (MIT). See assets/catalog-icons-LICENSE.txt. -->\n<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="64dp" android:height="64dp" android:viewportWidth="256" android:viewportHeight="256">\n${paths.join('\n')}\n</vector>\n`);
}
outputs.set('admin/app/catalog-icons.ts', `// Generated by npm run icons:generate. Source: shared/catalog-icons.\nexport const catalogIcons = ${JSON.stringify(icons, null, 2)} as const;\nexport const defaultCatalogIcon = 'game-controller';\nexport function catalogIconSrc(key: unknown): string {\n  return \`/catalog-icons/\${catalogIcons.find(icon => icon.key === key)?.key ?? defaultCatalogIcon}.svg\`;\n}\n`);
outputs.set('backend/src/games/catalog-icons.ts', `// Generated by npm run icons:generate. Source: shared/catalog-icons.\nexport const CATALOG_ICON_KEYS = ${JSON.stringify([...keys], null, 2)} as const;\n`);
outputs.set('android/app/src/main/java/com/yapnix/game/CatalogIcons.kt', `// Generated by npm run icons:generate. Source: shared/catalog-icons.\npackage com.yapnix.game\n\n/** Bundled vectors render offline; unknown future keys use the default icon. */\ninternal fun catalogIconResource(key: String): Int = when (key) {\n${icons.map(icon => `    "${icon.key}" -> R.drawable.catalog_${icon.key.replaceAll('-', '_')}`).join('\n')}\n    else -> R.drawable.catalog_game_controller\n}\n`);
const license = await readFile(new URL('shared/catalog-icons/LICENSE', root), 'utf8');
outputs.set('admin/public/catalog-icons/LICENSE.txt', license);
outputs.set('android/app/src/main/assets/catalog-icons-LICENSE.txt', license);
const migrations = (await readdir(new URL('supabase/migrations/', root))).filter(file => file.endsWith('.sql')).sort().reverse();
let checkedSql = false;
for (const file of migrations) {
  const sql = await readFile(new URL(`supabase/migrations/${file}`, root), 'utf8');
  const constraints = [...sql.matchAll(/icon_key in \(([^)]+)\)/g)];
  if (!constraints.length) continue;
  for (const [, values] of constraints) {
    const sqlKeys = values.match(/'([^']+)'/g)?.map(value => value.slice(1, -1));
    if (JSON.stringify(sqlKeys) !== JSON.stringify([...keys])) throw new Error(`${file} icon allowlist differs from the catalogue`);
  }
  checkedSql = true;
  break;
}
if (!checkedSql) throw new Error('Missing database icon allowlist');
for (const [file, content] of outputs) {
  const target = new URL(file, root);
  if (process.argv.includes('--check')) {
    if (await readFile(target, 'utf8').catch(() => '') !== content) throw new Error(`${file} is stale; run npm run icons:generate`);
  } else {
    await mkdir(new URL('./', target), { recursive: true });
    await writeFile(target, content);
  }
}
console.log(`${icons.length} catalogue icons ${process.argv.includes('--check') ? 'verified' : 'generated'} for Studio, Android and the API.`);
